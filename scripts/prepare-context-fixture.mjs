import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
const web=path.resolve(import.meta.dirname,'../forks/pi-web');
const agent=process.argv[2];
if(!agent || !/^\/(?:private\/)?tmp\//.test(agent)) throw Error('Use an isolated /tmp agent');
execFileSync(process.execPath,[web+'/scripts/prepare-permission-fixture.mjs',agent],{stdio:'inherit'});
const save=(file,value)=>fs.writeFileSync(file,JSON.stringify(value,null,2)+'\n');
const settings=JSON.parse(fs.readFileSync(agent+'/settings.json'));
settings.defaultTools=['write','bash'];save(agent+'/settings.json',settings);
const outside=agent+'/outside';fs.mkdirSync(outside);
fs.writeFileSync(outside+'/probe.txt','CONTEXT_CACHE_FIXTURE_READ');
fs.writeFileSync(outside+'/blocked.txt','CONTEXT_FIXTURE_MUST_NOT_BE_READ');
const configFile=agent+'/extensions/pi-permission-system/config.json';
const config=JSON.parse(fs.readFileSync(configFile));
config.permission.path_read={'*':'ask',[outside+'/blocked.txt']:'deny'};
config.permission.external_directory_read={'*':'ask'};
save(configFile,config);
let provider=fs.readFileSync(agent+'/fixture.ts','utf8');
provider="import {appendFileSync} from 'node:fs';\n"+provider;
provider=provider.replace("if(isReview) {",`if(isReview) {appendFileSync(${JSON.stringify(agent+'/review-count.jsonl')},JSON.stringify({outcome,time:Date.now()})+'\\n');`);
provider=provider.replace("if(last.role==='user') {",`if(last.role==='user' && text.startsWith('bash-')) {outcome='allow';return fauxAssistantMessage([fauxToolCall('bash',{command:'cat '+${JSON.stringify(outside)}+(text.startsWith('bash-deny')?'/blocked.txt':'/probe.txt')})]);}\n     if(last.role==='user') {`);
fs.writeFileSync(agent+'/fixture.ts',provider);
console.log(JSON.stringify({agent,workspace:agent+'/workspace',outside}));
